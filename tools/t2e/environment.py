"""Environment metadata, setup script, and isolated check execution
(issue #2).

environment.json records observed versions (from the retained evidence),
selected versions (what this environment actually provides), unknowns,
and every deviation — Node 26.8.2 takes precedence over the starting
mise.toml declaration of 24. setup.sh performs dependency setup only;
its outputs (node_modules) never count toward source identity.
"""

from __future__ import annotations

import os
import platform
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .canonical import sha256_file, write_text_atomic

CHECK_TIMEOUT_S = 600
SETUP_TIMEOUT_S = 900

OBSERVED_NODE = "v26.8.2"
OBSERVED_PNPM = "11.6.0"
DECLARED_NODE = "24"  # starting mise.toml
SELECTED_PNPM = "11.6.0"  # packageManager field, resolved by corepack

SETUP_SH = """#!/bin/sh
# Dependency setup only. Generated by t2e (spike-trace2eval).
# pnpm 11.6.0 is resolved from the package's packageManager field via
# corepack; install flags match the original run.
set -eu
export COREPACK_ENABLE_DOWNLOAD_PROMPT=0
cd "$(dirname "$0")/source"
corepack pnpm install --frozen-lockfile --ignore-scripts
"""


@dataclass
class CheckOutcome:
    name: str
    command: str
    required: bool
    exit_code: int | None
    stdout_ref: dict[str, Any] | None = None
    stderr_ref: dict[str, Any] | None = None
    error: str | None = None


def _probe(cmd: list[str]) -> str | None:
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return out.stdout.strip() or out.stderr.strip() or None


def probe_environment(source_dir: Path | None = None, path_prefix: str | None = None) -> dict[str, Any]:
    """Selected versions actually available here, plus recorded deviations."""
    env = dict(os.environ)
    if path_prefix:
        env["PATH"] = f"{path_prefix}:{env.get('PATH', '')}"
    try:
        out = subprocess.run(["node", "--version"], capture_output=True, text=True, timeout=30, env=env)
        node = out.stdout.strip() or None
    except (OSError, subprocess.TimeoutExpired):
        node = None
    try:
        out = subprocess.run(
            ["corepack", "pnpm", "--version"],
            cwd=source_dir if source_dir is not None else Path.cwd(),
            capture_output=True, text=True, timeout=120,
            env={**env, "COREPACK_ENABLE_DOWNLOAD_PROMPT": "0"},
        )
        pnpm = out.stdout.strip() or None
    except (OSError, subprocess.TimeoutExpired):
        pnpm = None
    return {
        "node": node,
        "pnpm": pnpm,
        "os": f"{platform.system()} {platform.release()} ({platform.machine()})",
        "python": platform.python_version(),
    }


def build_environment_json(selected: dict[str, Any]) -> dict[str, Any]:
    deviations = []
    if selected.get("node") != OBSERVED_NODE:
        deviations.append({
            "item": "node",
            "observed": OBSERVED_NODE,
            "declared_in_mise_toml": DECLARED_NODE,
            "selected": selected.get("node"),
            "note": "observed runtime takes precedence over the starting mise.toml declaration; an exact install was not present locally",
        })
    else:
        deviations.append({
            "item": "node",
            "observed": OBSERVED_NODE,
            "declared_in_mise_toml": DECLARED_NODE,
            "selected": selected.get("node"),
            "note": "observed runtime takes precedence over the starting mise.toml declaration of 24",
        })
    deviations.append({
        "item": "pnpm",
        "observed": OBSERVED_PNPM,
        "selected": selected.get("pnpm"),
        "note": "pinned by the packageManager field via corepack",
    })
    return {
        "schema_version": 1,
        "observed": {
            "node": OBSERVED_NODE,
            "pnpm": OBSERVED_PNPM,
            "os_family": "inferred macOS (path shape in trace; exact version unknown)",
            "dependency_cache": "warm — original install reused a populated store",
        },
        "selected": {
            "node": selected.get("node"),
            "pnpm": selected.get("pnpm"),
            "os": selected.get("os"),
            "dependency_cache": "as provided by the local pnpm store; not prewarmed by this tooling",
        },
        "unknowns": [
            "exact OS version and build",
            "complete PATH and environment variables",
            "locale settings",
            "internal harness instructions and full model input",
        ],
        "deviations": deviations,
        "notes": [
            "Source files come from the pinned starting commit only; dependency outputs are produced by setup.sh and are not part of the starting source.",
            "Node 26.8.2 takes precedence over the starting mise.toml declaration of 24.",
        ],
    }


def write_setup_sh(case_agent_dir: Path) -> Path:
    path = case_agent_dir / "setup.sh"
    write_text_atomic(path, SETUP_SH)
    path.chmod(0o755)
    return path


def _run_logged(cmd: str, cwd: Path, log_dir: Path, name: str, timeout: int, env: dict[str, str]) -> CheckOutcome:
    """Run a check, persisting bounded references (sha256+bytes) of output."""
    stdout_log = log_dir / f"{name}.stdout.txt"
    stderr_log = log_dir / f"{name}.stderr.txt"
    outcome = CheckOutcome(name=name, command=cmd, required=True, exit_code=None)
    try:
        proc = subprocess.run(
            ["sh", "-c", cmd], cwd=cwd, capture_output=True, text=True, timeout=timeout, env=env,
        )
    except subprocess.TimeoutExpired:
        outcome.error = f"timeout after {timeout}s"
        return outcome
    stdout_log.parent.mkdir(parents=True, exist_ok=True)
    stdout_log.write_text(proc.stdout, encoding="utf-8")
    stderr_log.write_text(proc.stderr, encoding="utf-8")
    outcome.exit_code = proc.returncode
    outcome.stdout_ref = {"file": stdout_log.name, "sha256": sha256_file(stdout_log), "bytes": len(proc.stdout.encode())}
    outcome.stderr_ref = {"file": stderr_log.name, "sha256": sha256_file(stderr_log), "bytes": len(proc.stderr.encode())}
    return outcome


def run_setup_and_checks(
    source_dir: Path,
    log_dir: Path,
    checks: list[dict[str, Any]],
    path_prefix: str | None = None,
) -> dict[str, Any]:
    """Run dependency setup, then each declared check, in `source_dir`.

    Setup and checks run inside an isolated copy — never inside the
    pristine case source. Exit codes and bounded output references are
    recorded for all checks; existing-check success alone does not
    establish task completion.
    """
    env = {**os.environ, "COREPACK_ENABLE_DOWNLOAD_PROMPT": "0"}
    if path_prefix:
        env["PATH"] = f"{path_prefix}:{env.get('PATH', '')}"
    setup_out = subprocess.run(
        ["corepack", "pnpm", "install", "--frozen-lockfile", "--ignore-scripts"],
        cwd=source_dir, capture_output=True, text=True, timeout=SETUP_TIMEOUT_S, env=env,
    )
    (log_dir / "setup.stdout.txt").parent.mkdir(parents=True, exist_ok=True)
    (log_dir / "setup.stdout.txt").write_text(setup_out.stdout[-20000:], encoding="utf-8")
    (log_dir / "setup.stderr.txt").write_text(setup_out.stderr[-20000:], encoding="utf-8")
    setup = {
        "command": "corepack pnpm install --frozen-lockfile --ignore-scripts",
        "exit_code": setup_out.returncode,
        "stdout_ref": {"file": "setup.stdout.txt", "sha256": sha256_file(log_dir / "setup.stdout.txt")},
        "stderr_ref": {"file": "setup.stderr.txt", "sha256": sha256_file(log_dir / "setup.stderr.txt")},
    }
    results: dict[str, Any] = {"setup": setup, "checks": []}
    if setup_out.returncode != 0:
        return results
    for chk in checks:
        outcome = _run_logged(chk["command"], source_dir, log_dir, chk["name"], int(chk.get("timeout_seconds", CHECK_TIMEOUT_S)), env)
        outcome.required = bool(chk.get("required", True))
        results["checks"].append({
            "name": outcome.name,
            "command": outcome.command,
            "required": outcome.required,
            "exit_code": outcome.exit_code,
            "error": outcome.error,
            "stdout_ref": outcome.stdout_ref,
            "stderr_ref": outcome.stderr_ref,
        })
    return results
